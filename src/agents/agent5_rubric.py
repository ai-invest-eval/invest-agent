def get_rubric(question: str, business_model: str | None) -> tuple[str, dict]:
    if question == "QD":
        return QD_RUBRIC.get(business_model or "", QD_RUBRIC["pipeline"])
    return RUBRIC[question]


def rubric_text(questions: list[str], business_model: str | None) -> str:
    lines = []
    for q in questions:
        name, levels = get_rubric(q, business_model)
        lines.append(f"[{q}] {name}")
        lines.extend(f"  {s}점: {levels[s]}" for s in (5, 4, 3, 2, 1))
        if q in EXTRA_NOTES:
            lines.append(f"  ※ {EXTRA_NOTES[q]}")
    return "\n".join(lines)


